#!/usr/bin/env python3
"""Generate every contract of this bundle from tests/reference/op_specs.py.

Output (all generated, never edited by hand):

* ``contracts/operation_manifest.yaml`` — every operation
* ``contracts/step_ui_manifest.yaml``   — the builder form of every operation
* ``contracts/artifact_policies.yaml``  — file inputs and outputs
* ``ui/actions/actions.yaml``           — the same-id workflow-visible actions
* ``ui/pages/finvalda-api.yaml``, ``ui/pages/coverage.yaml``, ``ui/pages/changelog.yaml``
* ``runtime/registry.json``             — what the runtime needs per operation, the
  manual's field tables and error texts
* ``tests/reference/coverage.json``     — every documented method, type and class → the
  operation that offers it, or why none does
* ``extension.yaml`` ``external_effects`` block

Run from the bundle root:  python3 tests/reference/build_contracts.py
``tests/test_contracts.py`` fails when the committed files drift from this output.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import build_ui_pages  # noqa: E402
import op_specs  # noqa: E402

CONNECTION_TYPE_ID = "finvalda"
CATEGORY = "finance"
CHANNEL = "finvalda_web_service"
GENERATED_HEADER = (
    "# Generated by tests/reference/build_contracts.py from tests/reference/op_specs.py.\n"
    "# Do not edit by hand: tests/test_contracts.py fails when this file drifts.\n"
)
UPLOAD_BINDING = "finvalda_upload"
DOWNLOAD_BINDING = "finvalda_file"
EXPORT_BINDING = "finvalda_export"
MAX_UPLOAD_BYTES = 8 * 1024 * 1024
MAX_DOWNLOAD_BYTES = 40 * 1024 * 1024
MAX_EXPORT_BYTES = 200 * 1024 * 1024
DOWNLOAD_CONTENT_TYPE = "application/octet-stream"
EXPORT_CONTENT_TYPE = "application/x-ndjson"
EXPORT_FILENAME = "finvalda-export.jsonl"
FILE_FIELD_HELP = "A workflow file, e.g. the invoice PDF from an earlier step, up to 8 MB."
TEXTAREA_INPUTS = {"notes", "file_description"}

BASE_ERRORS = [
    "invalid_payload",
    "invalid_host_envelope",
    "invalid_connection",
    "unsupported_operation",
    "internal_error",
]
TRANSPORT_ERRORS = [
    "authentication_failed",
    "not_found",
    "conflict",
    "upstream_validation_failed",
    "upstream_failure",
    "invalid_response",
    "response_too_large",
    "timeout",
    "connection_failed",
    "redirect_rejected",
    "blocked_address",
]


def effect_outputs() -> list[dict[str, Any]]:
    return [
        {"name": "external_effect_status", "value_type": "text", "schema": {"type": "string"}},
        {
            "name": "definitely_no_external_effect",
            "value_type": "boolean",
            "schema": {"type": "boolean"},
        },
    ]


def errors_for(spec: dict[str, Any]) -> list[str]:
    codes = [*BASE_ERRORS, *TRANSPORT_ERRORS]
    if spec["kind"] == "action":
        codes.append("timeout_unknown")
    inputs = {i["value_type"] for i in spec["inputs"]}
    outputs = {o["value_type"] for o in spec["outputs"]}
    if "artifact_handle" in inputs:
        codes.append("artifact_input_unavailable")
    if "artifact_handle" in outputs:
        codes.append("artifact_output_unavailable")
    return codes


def _clean_input(item: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in item.items() if k != "labels"}


def operation(spec: dict[str, Any]) -> dict[str, Any]:
    write = spec["kind"] == "action"
    op: dict[str, Any] = {
        "operation_id": spec["operation_id"],
        "display_name": spec["display_name"],
        "description": spec["description"],
        "operation_kind": spec["kind"],
        "category": CATEGORY,
        "connection_type_ids": [CONNECTION_TYPE_ID],
        "workflow_visible": True,
    }
    if write:
        op["effect_kind"] = f"finvalda_{spec['operation_id']}"
    outputs = list(spec["outputs"]) + (effect_outputs() if write else [])
    op["inputs"] = [_clean_input(i) for i in spec["inputs"]]
    op["outputs"] = outputs
    op["result_fields"] = [f"result.{o['name']}" for o in outputs]
    op["error_codes"] = errors_for(spec)
    return op


ACTION_PARAM_TYPES = {
    "connection_ref": "connection_ref",
    "text": "string",
    "integer": "integer",
    "number": "number",
    "boolean": "boolean",
    "object": "object",
    "array": "array",
    "artifact_handle": "artifact_handle",
}


def action_for(op: dict[str, Any]) -> dict[str, Any]:
    write = op["operation_kind"] == "action"
    action: dict[str, Any] = {
        "action_id": op["operation_id"],
        "title": op["display_name"],
        "description": op["description"],
        "required_scopes": ["extension:invoke"],
        "handler": {"mode": "extension"},
    }
    if write:
        action["command_type"] = "invoke_extension_action"
    action["mutates_platform"] = write
    action["workflow_visible"] = True
    action["parameters"] = [
        {
            "name": i["name"],
            "type": ACTION_PARAM_TYPES[i["value_type"]],
            "required": bool(i.get("required")),
        }
        for i in op["inputs"]
    ]
    action["result_fields"] = [o["name"] for o in op["outputs"]]
    action["error_codes"] = list(op["error_codes"])
    return action


def widget_for(item: dict[str, Any]) -> str:
    schema = item.get("schema") or {}
    if schema.get("enum"):
        return "select"
    if item["name"] in TEXTAREA_INPUTS:
        return "textarea"
    vt = item["value_type"]
    if vt in {"object", "array"}:
        return "json"
    if vt == "boolean":
        return "boolean"
    if vt in {"integer", "number"}:
        return "number"
    return "text"


FORM_PLACEHOLDERS = {
    (
        "create_sales_invoice",
        "lines",
    ): '[{"code":"PRODUCT01","quantity":2,"price":12.5,"warehouse":"MAIN"}]',
    ("find_or_create_client", "name"): "Example customer Ltd",
    ("find_or_create_product", "name"): "Example product",
    ("find_or_create_service", "name"): "Example service",
    ("changes_since", "since"): "2026-01-01",
}


def form_for(spec: dict[str, Any]) -> dict[str, Any]:
    fields = []
    for item in spec["inputs"]:
        if item["value_type"] == "connection_ref":
            continue
        if item["value_type"] == "artifact_handle":
            fields.append(
                {
                    "name": item["name"],
                    "label": "File",
                    "widget_type": "artifact_picker",
                    "required": bool(item.get("required")),
                    "help_text": FILE_FIELD_HELP,
                }
            )
            continue
        schema = item.get("schema") or {}
        field: dict[str, Any] = {
            "name": item["name"],
            "label": schema.get("title") or item["name"],
            "widget_type": widget_for(item),
            "required": bool(item.get("required")),
        }
        if schema.get("description"):
            field["help_text"] = schema["description"][:400]
        if schema.get("enum"):
            labels = item.get("labels") or {}
            field["options"] = [
                {"label": labels.get(v, str(v)), "value": v} for v in schema["enum"]
            ]
        example = FORM_PLACEHOLDERS.get((spec["operation_id"], item["name"]))
        if example is not None:
            field["placeholder"] = example
        fields.append(field)
    return {"operation_id": spec["operation_id"], "title": spec["display_name"], "fields": fields}


def artifact_policies(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    policies: list[dict[str, Any]] = []
    for op in ops:
        entry: dict[str, Any] = {"operation_id": op["operation_id"]}
        file_inputs = [i for i in op["inputs"] if i["value_type"] == "artifact_handle"]
        if file_inputs:
            entry["inputs"] = [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": UPLOAD_BINDING,
                    "field": i["name"],
                    "required": bool(i.get("required")),
                    "max_size_bytes": MAX_UPLOAD_BYTES,
                }
                for i in file_inputs
            ]
        file_outputs = [o for o in op["outputs"] if o["value_type"] == "artifact_handle"]
        if file_outputs and op["operation_id"] == "export_list":
            entry["outputs"] = [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": EXPORT_BINDING,
                    "filename": EXPORT_FILENAME,
                    "content_type": EXPORT_CONTENT_TYPE,
                    "max_size_bytes": MAX_EXPORT_BYTES,
                    "max_size_env": "FS_EXTENSION_ARTIFACT_MAX_BYTES",
                    "retention_class": "run_window",
                }
            ]
        elif file_outputs:
            entry["outputs"] = [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": DOWNLOAD_BINDING,
                    "filename": "finvalda-file.bin",
                    "content_type": DOWNLOAD_CONTENT_TYPE,
                    "max_size_bytes": MAX_DOWNLOAD_BYTES,
                    "retention_class": "run_window",
                }
            ]
        if len(entry) > 1:
            policies.append(entry)
    return policies


def external_effects(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            "operation_id": op["operation_id"],
            "effect_kind": op["effect_kind"],
            "channel": CHANNEL,
            "idempotency": "required",
            "test_mode_behavior": "suppress",
        }
        for op in ops
        if op["operation_kind"] == "action"
    ]


# ---------------------------------------------------------------------------
# Coverage: every documented name -> an operation, or why none

_NOT_METHODS = re.compile(r"(Response|Result|In|Out)$")


def coverage(specs: list[dict[str, Any]]) -> dict[str, Any]:
    ref = op_specs.reference()
    manual = ref["manual"]
    postman = ref["postman"]
    by_method: dict[str, str] = {}
    for spec in specs:
        runtime = spec.get("runtime") or {}
        method = runtime.get("method")
        if method and runtime.get("runner") not in {"descriptions", "operations", "export"}:
            by_method.setdefault(method, spec["operation_id"])
    by_method["GetDescriptions"] = "descriptions_clients"
    by_method["GetOperations"] = "operations_sales"
    by_method["GetAttachedDocuments"] = "attached_documents"
    special_reasons = {
        "GetFvsUser": (
            None,
            "Not offered: it takes another Finvalda user's name and password as parameters, and a "
            "workflow input is no place for a password. The connection's own user is checked by Test the connection.",
        ),
        "GetEinamiejiLikuciaiSandelyje": (
            "get_einamieji_likuciai",
            "Removed by the manual's revision 4; GetEinamiejiLikuciai takes the warehouse instead.",
        ),
        "GetUzsakytasPrekes": (
            "call_method",
            "Named only in the manual's revision history (revision 13), with no section and no "
            "parameters: reachable through Call a Finvalda method.",
        ),
        "EditItemsProps": ("edit_item_props", "The method list's spelling of EditItemProps."),
        "GetAttachedDocument": (
            "attached_documents",
            "The Pure interface's name of GetAttachedDocuments.",
        ),
        "DeleteDokumentas": ("delete_document", "The revision history's name of DeleteDocument."),
        "IsOperatonLocked": (
            "is_operation_locked",
            "A misspelling of IsOperationLocked in the revision history.",
        ),
        "GetKlientuSet": (
            "get_klientus_set",
            "A misspelling of GetKlientusSet in the revision history.",
        ),
        "GetMokeciai": ("get_mokesciai", "A misspelling of GetMokesciai in a signature."),
        "GetPalsaugosSet": (
            "get_paslaugos_set",
            "A misspelling of GetPaslaugosSet in a signature.",
        ),
        "InsertNew": ("insert_operation", "Short for InsertNewOperation in the revision history."),
        "IsLocked": ("is_operation_locked", "The answer field of IsOperationLocked, not a method."),
    }
    entries: dict[str, dict[str, Any]] = {}

    def add(name: str, operation: str | None, reason: str, sources: list[str]) -> None:
        entry = entries.setdefault(name, {"operation": operation, "reason": reason, "sources": []})
        for source in sources:
            if source not in entry["sources"]:
                entry["sources"].append(source)

    names: dict[str, list[str]] = {}
    types = op_specs.description_types()
    for name, info in manual["methods"].items():
        if info["section"].startswith("4.") and name != "GetDescriptions":
            if name not in types:
                # A section heading spelled unlike its type (TagsAndTypes, WareHouseGroups).
                kind = next(
                    t
                    for t in types
                    if t.lower() == name.lower()
                    or sorted(op_specs.words(t).split()) == sorted(op_specs.words(name).split())
                )
                add(
                    f"GetDescriptions:{name}",
                    f"descriptions_{op_specs.snake(kind)}",
                    f"The manual's section heading; the type it describes is {kind}.",
                    ["manual"],
                )
            continue
        names.setdefault(name, []).append("manual")
    for name in manual["listed_methods"]:
        names.setdefault(name, []).append("manual list")
    for name in manual["mentioned_methods"]:
        if not _NOT_METHODS.search(name) or name in by_method:
            names.setdefault(name, []).append("manual text")
    for name in postman["endpoints"]:
        names.setdefault(name, []).append("postman")
    for name, sources in sorted(names.items()):
        if name in special_reasons:
            operation, reason = special_reasons[name]
        elif name.endswith("Xml") and name[:-3] in by_method:
            operation = by_method[name[:-3]]
            reason = f"The same data as {name[:-3]} as an XML string; that step returns it as JSON."
        elif name in by_method:
            operation, reason = by_method[name], ""
        else:
            raise SystemExit(f"coverage: no operation for documented method {name}")
        add(f"method:{name}", operation, reason, sources)
    for kind, info in op_specs.description_types().items():
        add(
            f"GetDescriptions:{kind}",
            f"descriptions_{op_specs.snake(kind)}",
            "",
            ["manual" if info["source"] == "manual" else "postman"],
        )
    for op_class, info in op_specs.operation_classes().items():
        add(
            f"GetOperations:{op_class}",
            f"operations_{op_specs.snake(op_class)}",
            "",
            ["manual" if info["source"] == "manual" else "postman"],
        )
    item_classes = op_specs.item_classes() + op_specs.POSTMAN_ITEM_CLASSES
    for cls in manual["classes"]:
        if cls in item_classes:
            add(f"class:{cls}", "insert_item", "", ["manual"])
        elif cls in op_specs.PROPS_CLASSES:
            add(f"class:{cls}", "edit_item_props", "", ["manual"])
        elif cls in op_specs.LINE_CLASSES or any(cls in v for v in op_specs.LINE_CLASSES.values()):
            add(f"class:{cls}", "insert_operation", "", ["manual"])
        elif cls in op_specs.UPDATE_CLASSES or any(
            cls in v for v in op_specs.UPDATE_CLASSES.values()
        ):
            add(f"class:{cls}", "update_operation", "", ["manual"])
        elif cls in op_specs.DELETE_CLASSES:
            add(f"class:{cls}", "delete_operation", "", ["manual"])
        else:
            raise SystemExit(f"coverage: no operation for documented class {cls}")
    for cls in op_specs.POSTMAN_ITEM_CLASSES:
        add(
            f"class:{cls}",
            "insert_item",
            "Field names come from the Postman example only.",
            ["postman"],
        )
    for alias, cls in op_specs.CLASS_ALIASES.items():
        add(
            f"class:{alias}",
            "insert_operation",
            f"The method's class list name; its fields are those of {cls}.",
            ["manual"],
        )
    return {
        "sources": ref["sources"],
        "entries": dict(sorted(entries.items())),
    }


def callable_methods(cov: dict[str, Any]) -> list[str]:
    """Every documented method name Call a Finvalda method may call."""
    names = set()
    for key, entry in cov["entries"].items():
        if not key.startswith("method:"):
            continue
        name = key.split(":", 1)[1]
        if entry["operation"] is None:
            continue
        if entry["reason"].startswith(
            (
                "A misspelling",
                "Short for",
                "The answer field",
                "The revision history",
                "Removed",
                "The method list",
            )
        ):
            continue
        names.add(name)
    names.add("GetAttachedDocument")
    return sorted(names)


def registry(specs: list[dict[str, Any]], cov: dict[str, Any]) -> dict[str, Any]:
    ref = op_specs.reference()
    classes = {}
    for name, fields in ref["manual"]["classes"].items():
        classes[name] = [
            {
                "name": f["name"],
                "type": f["type"],
                "length": f["length"],
                "required": f["required"],
                "from_parameter": f["from_parameter"],
            }
            for f in fields
        ]
    return {
        "sources": ref["sources"],
        "operations": {
            spec["operation_id"]: spec["runtime"] for spec in specs if spec.get("runtime")
        },
        "classes": classes,
        "errors": ref["manual"]["errors"],
        "callable_methods": callable_methods(cov),
        "change_entities": op_specs.CHANGE_ENTITIES,
        "description_types": op_specs.description_types(),
    }


def dump(path: Path, payload: Any) -> None:
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(GENERATED_HEADER + text, encoding="utf-8")


def dump_json(path: Path, payload: Any) -> None:
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=1, sort_keys=False) + "\n", encoding="utf-8"
    )


def splice_effects(effects: list[dict[str, Any]]) -> None:
    """Replace ``external_effects`` in extension.yaml, keeping every other key and its order."""
    manifest = ROOT / "extension.yaml"
    data = yaml.safe_load(manifest.read_text(encoding="utf-8"))
    rebuilt: dict[str, Any] = {}
    for key, value in data.items():
        if key == "runtime" and "external_effects" not in rebuilt:
            rebuilt["external_effects"] = effects
        if key != "external_effects":
            rebuilt[key] = value
    rebuilt.setdefault("external_effects", effects)
    # The same form ``flow-steward extensions lock-deps`` writes, so either tool
    # leaves the other's output unchanged.
    manifest.write_text(yaml.safe_dump(rebuilt, sort_keys=False), encoding="utf-8")


def outputs() -> dict[str, Any]:
    specs = op_specs.operations()
    ops = [operation(spec) for spec in specs]
    ids = [op["operation_id"] for op in ops]
    names = [op["display_name"] for op in ops]
    if len(ids) != len(set(ids)) or len(names) != len(set(names)):
        raise SystemExit("duplicate operation ids or step titles")
    cov = coverage(specs)
    return {
        "specs": specs,
        "operations": ops,
        "actions": [action_for(op) for op in ops],
        "forms": [form_for(spec) for spec in specs],
        "artifact_policies": artifact_policies(ops),
        "effects": external_effects(ops),
        "coverage": cov,
        "registry": registry(specs, cov),
        "api_page": build_ui_pages.api_page(ops, specs),
        "coverage_page": build_ui_pages.coverage_page(cov, ops),
        "changelog_page": build_ui_pages.changelog_page(),
    }


def main() -> None:
    built = outputs()
    dump(ROOT / "contracts" / "operation_manifest.yaml", {"operations": built["operations"]})
    dump(ROOT / "contracts" / "step_ui_manifest.yaml", {"forms": built["forms"]})
    dump(
        ROOT / "contracts" / "artifact_policies.yaml",
        {"artifact_policies": built["artifact_policies"]},
    )
    dump(ROOT / "ui" / "actions" / "actions.yaml", {"actions": built["actions"]})
    for name, key in (
        ("finvalda-api.yaml", "api_page"),
        ("coverage.yaml", "coverage_page"),
        ("changelog.yaml", "changelog_page"),
    ):
        build_ui_pages.dump_page(ROOT / "ui" / "pages" / name, GENERATED_HEADER, built[key])
    dump_json(ROOT / "runtime" / "registry.json", built["registry"])
    dump_json(HERE / "coverage.json", built["coverage"])
    splice_effects(built["effects"])
    print(
        f"{len(built['operations'])} operations, {len(built['effects'])} external effects, "
        f"{len(built['coverage']['entries'])} documented names covered"
    )


if __name__ == "__main__":
    main()
