"""What the runtime knows about Finvalda's web service, read from ``registry.json``.

``registry.json`` is generated by ``tests/reference/build_contracts.py`` from the
manual and the Postman collection (``tests/reference/fvs_reference.json``):

* ``OPERATIONS`` — how each Advanced step calls Finvalda (method, verb, parameters,
  list type or operation class, the filter names the manual documents);
* ``CLASSES`` — the manual's field tables of record and operation classes, used to
  check fields before anything is sent;
* ``ERROR_MEANINGS`` — the manual's text for each Finvalda result code;
* ``CALLABLE_METHODS`` — every documented method name Call a Finvalda method accepts.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_DATA: dict[str, Any] = json.loads(
    (Path(__file__).resolve().parent / "registry.json").read_text(encoding="utf-8")
)

SOURCES: dict[str, Any] = _DATA["sources"]
OPERATIONS: dict[str, dict[str, Any]] = _DATA["operations"]
CLASSES: dict[str, list[dict[str, Any]]] = _DATA["classes"]
ERROR_MEANINGS: dict[str, str] = _DATA["errors"]
CALLABLE_METHODS: frozenset[str] = frozenset(_DATA["callable_methods"])
CHANGE_ENTITIES: dict[str, list[str]] = _DATA["change_entities"]
DESCRIPTION_TYPES: dict[str, dict[str, Any]] = _DATA["description_types"]

__all__ = [
    "CALLABLE_METHODS",
    "CHANGE_ENTITIES",
    "CLASSES",
    "DESCRIPTION_TYPES",
    "ERROR_MEANINGS",
    "OPERATIONS",
    "SOURCES",
]
